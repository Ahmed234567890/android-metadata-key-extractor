#!/usr/bin/env python3
"""Generate analysis/01-symbol-map.md from modules/pvrsrvkm.ko.

    ./scripts/symbols.py > analysis/01-symbol-map.md

Only symbols of type FUNC with a non-zero size are counted, which is what the
kernel's kallsyms and the disassembler agree on. The file is a relocatable
object, so st_value is a section offset; sizes are exact because the compiler
emitted them.
"""
import subprocess
import sys
from collections import defaultdict

from elftools.elf.elffile import ELFFile

MODULE = "modules/pvrsrvkm.ko"

# Ordered: the first prefix that matches wins.
CATEGORIES = [
    ("pvr_drm_* (DRM glue)",            ("pvr_drm_",)),
    ("PVRSRVBridge* (bridge entry)",    ("PVRSRVBridge",)),
    ("Bridge* (bridge helpers)",        ("Bridge", "_Bridge")),
    ("MMU_*",                           ("MMU_",)),
    ("RGX*",                            ("RGX", "Rgx", "_RGX", "_Rgx")),
    ("Devmem*",                         ("Devmem", "_Devmem", "PVRSRVDevmem")),
    ("PMR*",                            ("PMR", "_PMR", "Physmem")),
    ("Sync*",                           ("Sync", "_Sync")),
    ("Cache*",                          ("Cache", "_Cache", "SLC")),
    ("Heap*",                           ("Heap", "_Heap", "HeapCfg")),
    ("OS* (OS abstraction)",            ("OS", "_OS", "PVRSRVOS")),
    ("HTB* (host trace buffer)",        ("HTB", "_HTB")),
    ("DMA / dma-buf",                   ("DMA", "Dma", "_DMA", "DmaBuf", "DMABUF")),
    ("Init / Deinit",                   ("Init", "Deinit", "_Init", "_Deinit")),
    ("other PVRSRV*",                   ("PVRSRV",)),
]


def category(name):
    for label, prefixes in CATEGORIES:
        if any(name.startswith(p) for p in prefixes):
            return label
    if name.startswith("_"):
        return "other static (_*)"
    return "other"


def main():
    with open(MODULE, "rb") as fh:
        elf = ELFFile(fh)
        symtab = next(s for s in elf.iter_sections() if s["sh_type"] == "SHT_SYMTAB")
        exec_sections = [s for s in elf.iter_sections()
                         if s.name in (".text", ".init.text", ".exit.text")]
        exec_bytes = sum(s["sh_size"] for s in exec_sections)

        funcs = []
        for s in symtab.iter_symbols():
            if s["st_info"]["type"] != "STT_FUNC" or s["st_size"] == 0:
                continue
            funcs.append((s["st_size"], s.name, s["st_info"]["bind"]))

    funcs.sort(reverse=True)
    total = sum(sz for sz, _, _ in funcs)

    by_cat = defaultdict(lambda: [0, 0, []])
    for sz, name, bind in funcs:
        c = by_cat[category(name)]
        c[0] += 1
        c[1] += sz
        c[2].append((sz, name))

    build_id = subprocess.run(
        ["readelf", "-n", MODULE], capture_output=True, text=True
    ).stdout
    build_id = next((l.split("Build ID:")[1].strip() for l in build_id.splitlines()
                     if "Build ID:" in l), "?")

    out = sys.stdout
    out.write("# 01 - Symbol map of `pvrsrvkm.ko`\n\n")
    out.write("Generated by `scripts/symbols.py` from `modules/pvrsrvkm.ko`\n")
    out.write("(build ID `%s`, sha256 `6843bf0e...`). Counts are symbols of type\n" % build_id)
    out.write("`STT_FUNC` with a non-zero `st_size`.\n\n")
    out.write("| | |\n| --- | --- |\n")
    out.write("| functions with a size | %d |\n" % len(funcs))
    out.write("| total function bytes | %d |\n" % total)
    out.write("| `.text` + `.init.text` + `.exit.text` | %d |\n" % exec_bytes)
    out.write("| functions per KiB of executable code | %.2f |\n\n"
              % (len(funcs) / (exec_bytes / 1024)))

    out.write("## By subsystem\n\n")
    out.write("| Subsystem | Functions | Bytes | Share of function bytes | Largest |\n")
    out.write("| --- | ---: | ---: | ---: | --- |\n")
    for label, (n, sz, entries) in sorted(by_cat.items(), key=lambda kv: -kv[1][1]):
        biggest = max(entries)[1]
        out.write("| %s | %d | %d | %.1f%% | `%s` |\n"
                  % (label, n, sz, 100.0 * sz / total, biggest))

    out.write("\n## Largest functions\n\n")
    out.write("| Bytes | Symbol | Category |\n| ---: | --- | --- |\n")
    for sz, name, bind in funcs[:25]:
        out.write("| %d | `%s` | %s |\n" % (sz, name, category(name)))

    out.write("\n## The probe points\n\n")
    out.write("These are the symbols `scripts/trace.sh` attaches to, with the reason\n")
    out.write("each one is interesting.\n\n")
    out.write("| Symbol | Bytes | Why |\n| --- | ---: | --- |\n")
    wanted = {
        "pvr_drm_open": "one event per process that opens the render node",
        "pvr_drm_release": "pairs with open; shows the fd lifetime",
        "BridgedDispatchKM": "every ioctl that reaches the bridge",
        "MMU_CheckFaultAddress": "first stop on a GPU page fault",
        "RGXCheckFaultAddress": "firmware-reported fault, after the MMU",
        "DevmemIntGetFaultAddress": "reads back the faulting address",
        "RGXPrePowerState": "power-down of the RGX core",
        "RGXPostPowerState": "power-up of the RGX core",
        "PVRSRVDeviceIdleRequestKM": "idle entry requested by the driver",
        "PVRSRVDeviceIdleCancelRequestKM": "idle entry cancelled",
        "RGXPreClockSpeedChange": "DVFS down",
        "RGXPostClockSpeedChange": "DVFS up",
    }
    sizes = {name: sz for sz, name, _ in funcs}
    for name in wanted:
        out.write("| `%s` | %s | %s |\n"
                  % (name, sizes.get(name, "?"), wanted[name]))


if __name__ == "__main__":
    main()
